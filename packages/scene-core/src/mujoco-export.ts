import { openableSpec, surfaceElevation } from "./actions.js";
import { D4, Wc as wallGeometry } from "./inherited/topology.js";
import { furnitureElevation } from "./placement.js";
import type { Furniture, Plan } from "./types.js";

export interface MujocoExportOptions {
  /** Include <freejoint/> on unanchored freestanding floor furniture (default: true). */
  dynamicFurniture?: boolean;
  /** Scene model name in MJCF root attribute. */
  modelName?: string;
}

function xmlEscape(value: string): string {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function safeName(prefix: string, rawId: string, index: number): string {
  const cleaned = String(rawId || "")
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .slice(0, 40);
  return `${prefix}_${cleaned || index}_${index}`;
}

function hexToRgba(hex: string | undefined, alpha = 1): string {
  const match = /^#?([0-9a-fA-F]{6})$/.exec((hex || "").trim());
  if (!match) return `0.76 0.71 0.64 ${alpha}`;
  const raw = match[1];
  const r = (parseInt(raw.slice(0, 2), 16) / 255).toFixed(3);
  const g = (parseInt(raw.slice(2, 4), 16) / 255).toFixed(3);
  const b = (parseInt(raw.slice(4, 6), 16) / 255).toFixed(3);
  return `${r} ${g} ${b} ${alpha}`;
}

const DOOR_TYPES = new Set([
  "door",
  "double",
  "unequal",
  "sliding",
  "folding",
  "pocket",
  "garage",
]);

const STATIC_FLOOR_COVERINGS = new Set([
  "rug",
  "roundRug",
  "curtain",
  "sheer",
]);

/**
 * Export an ActiScape Plan (mm, 2D +Y south) to a standard MuJoCo MJCF (.xml)
 * scene (meters, right-handed +X east, +Y north, +Z up) with doorway cutouts,
 * articulated door/cabinet hinge joints, and wall-anchoring constraints.
 */
export function exportPlanToMujocoXml(
  plan: Plan,
  options: MujocoExportOptions = {},
): string {
  const dynamicFurniture = options.dynamicFurniture ?? true;
  const modelName = xmlEscape(
    options.modelName || plan.name || "actiscape_home_digital_twin",
  );
  const wallHeightMm = plan.height || 2800;
  const geo = wallGeometry(plan);

  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (const v of plan.nodes) {
    minX = Math.min(minX, v.x);
    maxX = Math.max(maxX, v.x);
    minY = Math.min(minY, v.y);
    maxY = Math.max(maxY, v.y);
  }
  if (!Number.isFinite(minX)) {
    minX = 0;
    maxX = 5000;
    minY = 0;
    maxY = 4000;
  }
  const centerMx = (((minX + maxX) / 2) * 0.001).toFixed(4);
  const centerMy = (-((minY + maxY) / 2) * 0.001).toFixed(4);
  const planeHalfX = Math.max(6, ((maxX - minX) * 0.001) / 2 + 2).toFixed(3);
  const planeHalfY = Math.max(6, ((maxY - minY) * 0.001) / 2 + 2).toFixed(3);

  const lines: string[] = [];
  lines.push(`<?xml version="1.0" encoding="utf-8"?>`);
  lines.push(`<mujoco model="${modelName}">`);
  lines.push(
    `  <!-- Generated by ActiScape Spatial Gatekeeper & Embodied Digital Twin Exporter -->`,
  );
  lines.push(
    `  <compiler angle="degree" coordinate="local" inertiafromgeom="true"/>`,
  );
  lines.push(`  <option timestep="0.002" gravity="0 0 -9.81" integrator="implicitfast"/>`);
  lines.push(`  <default>`);
  lines.push(`    <geom friction="0.75 0.01 0.005" solref="0.015 1" solimp="0.9 0.95 0.001"/>`);
  lines.push(`  </default>`);
  lines.push(`  <visual>`);
  lines.push(
    `    <headlight ambient="0.42 0.42 0.44" diffuse="0.68 0.68 0.70" specular="0.15 0.15 0.15"/>`,
  );
  lines.push(`  </visual>`);
  lines.push(`  <worldbody>`);
  lines.push(
    `    <light name="sun_key" pos="${centerMx} ${centerMy} 4.2" dir="0.15 -0.2 -0.96" directional="true" diffuse="0.85 0.83 0.78"/>`,
  );
  lines.push(
    `    <geom name="floor_plane" type="plane" pos="${centerMx} ${centerMy} 0" size="${planeHalfX} ${planeHalfY} 0.05" rgba="0.82 0.75 0.65 1"/>`,
  );

  // 1. Structural walls segmented around openings so doors remain navigable
  geo.active.forEach((w: any, wIdx: number) => {
    const lengthMm: number = w.len;
    if (!(lengthMm > 10)) return;
    const thicknessM = Math.max(0.06, (w.t || 180) * 0.001);
    const heightM = Math.max(0.5, wallHeightMm * 0.001);
    const yawDeg = (-Math.atan2(w.u.y, w.u.x) * 180) / Math.PI;
    const ops = [...(w.ops || [])].sort((a: any, b: any) => a.s0 - b.s0);

    const spans: Array<{ s0: number; s1: number; z0: number; z1: number; tag: string }> = [];
    let cursor = 0;
    ops.forEach((op: any, opIdx: number) => {
      const s0 = Math.max(cursor, op.s0);
      const s1 = Math.min(lengthMm, op.s1);
      if (s0 - cursor > 25) {
        spans.push({
          s0: cursor,
          s1: s0,
          z0: 0,
          z1: wallHeightMm,
          tag: `seg_${opIdx}`,
        });
      }
      if (s1 - s0 > 25) {
        const sill = Math.max(0, op.o?.sill ?? 0);
        const head = Math.min(wallHeightMm, op.o?.head ?? 2100);
        if (sill > 25) {
          spans.push({
            s0,
            s1,
            z0: 0,
            z1: sill,
            tag: `sill_${opIdx}`,
          });
        }
        if (wallHeightMm - head > 25) {
          spans.push({
            s0,
            s1,
            z0: head,
            z1: wallHeightMm,
            tag: `lintel_${opIdx}`,
          });
        }
      }
      cursor = Math.max(cursor, s1);
    });
    if (lengthMm - cursor > 25) {
      spans.push({
        s0: cursor,
        s1: lengthMm,
        z0: 0,
        z1: wallHeightMm,
        tag: "tail",
      });
    }

    const wallBaseName = safeName("wall", w.w?.id || `w${wIdx}`, wIdx);
    spans.forEach((span, sIdx) => {
      const midAlong = (span.s0 + span.s1) / 2;
      const wx = (w.a.x + w.u.x * midAlong) * 0.001;
      const wy = -(w.a.y + w.u.y * midAlong) * 0.001;
      const wz = ((span.z0 + span.z1) / 2) * 0.001;
      const halfLen = ((span.s1 - span.s0) * 0.001) / 2;
      const halfThick = thicknessM / 2;
      const halfH = ((span.z1 - span.z0) * 0.001) / 2;
      lines.push(
        `    <geom name="${wallBaseName}_${span.tag}_${sIdx}" type="box" pos="${wx.toFixed(4)} ${wy.toFixed(4)} ${wz.toFixed(4)}" euler="0 0 ${yawDeg.toFixed(2)}" size="${halfLen.toFixed(4)} ${halfThick.toFixed(4)} ${halfH.toFixed(4)}" rgba="0.93 0.91 0.87 1"/>`,
      );
    });

    // Articulated room doors with hinge joints
    ops.forEach((op: any, opIdx: number) => {
      const opening = op.o;
      if (!opening || !DOOR_TYPES.has(opening.type)) return;
      const doorWidthMm = op.s1 - op.s0;
      if (doorWidthMm < 200) return;
      const doorHeightM = Math.max(0.8, ((opening.head ?? 2100) - (opening.sill ?? 0)) * 0.001);
      const hingeAlong = opening.hinge ? op.s1 : op.s0;
      const leafDir = opening.hinge ? -1 : 1;
      const hx = (w.a.x + w.u.x * hingeAlong) * 0.001;
      const hy = -(w.a.y + w.u.y * hingeAlong) * 0.001;
      const hz = ((opening.sill ?? 0) * 0.001) + doorHeightM / 2;
      const halfDoorW = (doorWidthMm * 0.001) / 2;
      const doorName = safeName("room_door", opening.id, wIdx * 100 + opIdx);
      const initialAngle = opening.open ? 78 : 0;
      lines.push(
        `    <body name="${doorName}" pos="${hx.toFixed(4)} ${hy.toFixed(4)} ${hz.toFixed(4)}" euler="0 0 ${(yawDeg + initialAngle).toFixed(2)}">`,
      );
      lines.push(
        `      <joint name="${doorName}_hinge" type="hinge" axis="0 0 1" range="0 90" damping="4.5"/>`,
      );
      lines.push(
        `      <geom name="${doorName}_leaf" type="box" pos="${(leafDir * halfDoorW).toFixed(4)} 0 0" size="${halfDoorW.toFixed(4)} 0.022 ${(doorHeightM / 2).toFixed(4)}" density="420" rgba="0.68 0.52 0.36 1"/>`,
      );
      lines.push(`    </body>`);
    });
  });

  // 2. Furniture rigid bodies + cabinet door hinge joints
  const rawRegions: any = D4(plan, geo);
  const regions: any[] = Array.isArray(rawRegions)
    ? rawRegions
    : rawRegions?.regions || [];
  plan.furniture.forEach((f: Furniture, idx: number) => {
    const baseElevMm =
      f.parentObjectId || f.placement === "surface" || f.opt?.surface === true
        ? surfaceElevation(plan, f)
        : furnitureElevation(f, plan, regions);
    const halfW = Math.max(0.015, (f.w * 0.001) / 2);
    const halfD = Math.max(0.015, (f.d * 0.001) / 2);
    const halfH = Math.max(0.01, (f.h * 0.001) / 2);
    const mx = f.x * 0.001;
    const my = -f.y * 0.001;
    const mz = baseElevMm * 0.001 + halfH;
    // Plan rot=0 faces south (-Y in MJCF); rotating +rot clockwise in 2D equals -rot around +Z
    const yawDeg = -(f.rot || 0);
    const bodyName = safeName("furn", f.id, idx);
    const anchored =
      Boolean(f.opt?.wallAnchored) ||
      f.placement === "wall" ||
      STATIC_FLOOR_COVERINGS.has(f.key);
    const rgba = hexToRgba(f.color, STATIC_FLOOR_COVERINGS.has(f.key) ? 0.85 : 1);
    const spec = openableSpec(f);

    lines.push(
      `    <body name="${bodyName}" pos="${mx.toFixed(4)} ${my.toFixed(4)} ${mz.toFixed(4)}" euler="0 0 ${yawDeg.toFixed(2)}">`,
    );
    if (dynamicFurniture && !anchored) {
      lines.push(`      <freejoint name="${bodyName}_free"/>`);
    }
    if (f.opt?.wallAnchored) {
      lines.push(
        `      <site name="${bodyName}_wall_anchor" pos="0 ${halfD.toFixed(4)} ${(halfH * 0.75).toFixed(4)}" size="0.035" rgba="0.12 0.56 0.96 1"/>`,
      );
    }

    if (spec && spec.mode === "hinge" && halfD > 0.08 && halfW > 0.08) {
      const carcassHalfD = Math.max(0.04, halfD - 0.012);
      const leafThick = 0.012;
      lines.push(
        `      <geom name="${bodyName}_carcass" type="box" pos="0 0.012 0" size="${halfW.toFixed(4)} ${carcassHalfD.toFixed(4)} ${halfH.toFixed(4)}" density="280" rgba="${rgba}"/>`,
      );
      // Front face in Plan rot=0 is +y (south), which maps to -Y in local MJCF coordinates
      const doorOpenDeg = f.opt?.open ? -75 : 0;
      lines.push(
        `      <body name="${bodyName}_door" pos="${(-halfW).toFixed(4)} ${(-halfD + leafThick).toFixed(4)} 0" euler="0 0 ${doorOpenDeg}">`,
      );
      lines.push(
        `        <joint name="${bodyName}_door_hinge" type="hinge" axis="0 0 -1" range="0 95" damping="1.8"/>`,
      );
      lines.push(
        `        <geom name="${bodyName}_door_leaf" type="box" pos="${halfW.toFixed(4)} 0 0" size="${halfW.toFixed(4)} ${leafThick} ${(halfH * 0.96).toFixed(4)}" density="320" rgba="${rgba}"/>`,
      );
      lines.push(`      </body>`);
    } else {
      lines.push(
        `      <geom name="${bodyName}_geom" type="box" size="${halfW.toFixed(4)} ${halfD.toFixed(4)} ${halfH.toFixed(4)}" density="260" rgba="${rgba}"/>`,
      );
    }
    lines.push(`    </body>`);
  });

  // 3. HarmonyOS mmWave radar sites if configured in safetyProfile
  const radarSensors: any[] =
    (plan.source as any)?.safetyProfile?.radarSensors || [];
  radarSensors.forEach((sensor: any, idx: number) => {
    if (!Number.isFinite(sensor?.x) || !Number.isFinite(sensor?.y)) return;
    const sx = (sensor.x * 0.001).toFixed(4);
    const sy = (-sensor.y * 0.001).toFixed(4);
    const sz = ((sensor.z || 2400) * 0.001).toFixed(4);
    const siteName = safeName("harmony_mmwave", sensor.id || "radar", idx);
    lines.push(
      `    <site name="${siteName}" pos="${sx} ${sy} ${sz}" size="0.055" rgba="0.06 0.78 0.52 0.95"/>`,
    );
  });

  lines.push(`  </worldbody>`);
  lines.push(`</mujoco>`);
  return lines.join("\n") + "\n";
}
